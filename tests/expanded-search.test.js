const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");

const context = { console };
context.globalThis = context;
vm.runInNewContext(fs.readFileSync("src/core/expanded-search.js", "utf8"), context);
const rules = context.RoomExpandedSearch;
const plain = (value) => JSON.parse(JSON.stringify(value));

assert.deepEqual(plain(rules.suggestProblem("デスク周りが狭い", "在宅ワーカー")), ["デスク収納ラック", "モニター台 収納", "デスク下 収納", "デスク上 収納", "在宅ワーク デスク収納"]);
assert.throws(() => rules.suggestRelated({ itemName: "収納ラック", categoryName: "収納" }, "compare"), /カテゴリを特定できません/);
assert.ok(rules.suggestRelated({ itemName: "収納ラック" }, "together")[0].includes("併用"));
assert.ok(rules.suggestRelated({ itemName: "収納ラック" }, "problem", "机が狭い")[0].includes("机が狭い"));
const pantsOrigin = { itemName: "ニューバランス メンズ ニットワイドテーパードパンツ", categoryName: "メンズファッション > ズボン・パンツ" };
const compareKeywords = plain(rules.suggestRelated(pantsOrigin, "compare"));
assert.deepEqual(compareKeywords, ["メンズ テーパードパンツ", "メンズ ニットパンツ", "メンズ ワイドパンツ", "メンズ ロングパンツ", "ニューバランス メンズ パンツ"]);
assert.throws(() => rules.suggestRelated({ itemName: "ニューバランス 30%OFF" }, "compare"), /カテゴリを特定できません/);
assert.deepEqual(plain(rules.suggestSeasonal("winter")), ["防寒 グッズ", "大掃除 便利", "年末年始 キッチン"]);
assert.deepEqual(plain(rules.validateKeywords(["語句 1", "語句 2", "語句 3", "語句 4", "語句 5"])).length, 5);
assert.throws(() => rules.validateKeywords(["重複", "重複"]));
assert.throws(() => rules.validateKeywords(["<script>"]));
assert.throws(() => rules.validateKeywords(["https://example.test"]));
assert.throws(() => rules.validateKeywords(Array(6).fill("語句")));

const expected = { requestId: "request-1", searchMode: "problem" };
const valid = { schemaVersion: 1, requestId: "request-1", searchMode: "problem", keywords: ["収納 ラック", "デスク 収納"] };
assert.deepEqual(plain(rules.parseCodexResult(JSON.stringify(valid), expected)), valid.keywords);
for (const bad of ["{", JSON.stringify({ ...valid, requestId: "wrong" }), JSON.stringify({ ...valid, searchMode: "related" }), JSON.stringify({ ...valid, schemaVersion: 2 }), JSON.stringify({ ...valid, keywords: ["https://example.test"] }), "x".repeat(8193)]) assert.throws(() => rules.parseCodexResult(bad, expected));

const products = [{ itemCode: "a" }, { itemCode: "b" }, { itemCode: "a" }, { itemCode: "c" }];
assert.deepEqual(plain(rules.mergeResults([products.slice(0, 2), products.slice(2)], (item) => item.itemCode).map((item) => item.itemCode)), ["a", "b", "c"]);
assert.equal(rules.supportedSelectionReason("通気性", { itemName: "靴", itemCaption: "通気性のある素材" }), "通気性");
assert.throws(() => rules.supportedSelectionReason("最安", { itemName: "靴", itemCaption: "通気性のある素材" }));
assert.equal(rules.supportedSelectionReason("", {}), "");
assert.equal(rules.suggestSelectionReason({ itemCaption: "机の上を整理できる収納ラック。人気の商品です。" }), "机の上を整理できる収納ラック");
assert.equal(rules.suggestSelectionReason({ itemCaption: "大人気の特別商品です。" }), "");
const longReason = rules.suggestSelectionReason({ itemCaption: `在宅勤務の環境づくりに役立つ多機能な商品です。${"詳しい説明です。".repeat(14)}机上を整理できる収納ラックです。` });
assert.equal(longReason, "机上を整理できる収納ラックです");
assert.ok(longReason.length < 50, "selection reason is a concise evidence excerpt, not a full description");
assert.deepEqual(plain(rules.classifyRelevance({ itemName: "猫用爪とぎ", itemCaption: "猫が使う爪とぎ" }, { problem: "デスク周りが狭い", keywords: ["デスク下 収納"] })), { status: "low", reason: "商品名・説明にデスク周辺の収納・整理との関連を確認できません。" });
assert.equal(rules.classifyRelevance({ itemName: "モニター台収納ラック" }, { problem: "デスク周りが狭い", keywords: ["モニター台 収納"] }).status, "relevant");
const compareContext = { searchMode: "related", relation: "compare", originProduct: pantsOrigin, keywords: ["30%OFF 比較"] };
assert.equal(rules.identifyProductCategory({ itemName: "ゴルフ用ヘッドカバー" }).key, "golf-head-cover");
assert.equal(rules.classifyRelevance({ itemName: "メンズ ニットパンツ" }, compareContext).status, "relevant", "same pants category is eligible for comparison");
assert.equal(rules.classifyRelevance({ itemName: "ゴルフ用ヘッドカバー", itemCaption: "30%OFF 比較" }, compareContext).status, "low", "promo wording cannot override a different category");
assert.equal(rules.classifyRelevance({ itemName: "メンズ スイングトップ" }, compareContext).status, "low", "outerwear is excluded from pants comparison");
assert.equal(rules.classifyRelevance({ itemName: "商品" }, compareContext).status, "review", "unknown candidate category remains for user review");
assert.equal(rules.classifyRelevance({ itemName: "商品" }, { keywords: ["30%OFF 比較"] }).status, "review", "discount and compare tokens alone are not relevance evidence");
assert.equal(rules.classifyRelevance({ itemName: "商品", itemCaption: "30％OFFでおすすめ" }, { keywords: ["30％OFF おすすめ"] }).status, "review", "full-width discount tokens are also ignored as relevance evidence");
const searchContext = plain(rules.makeSearchContext({ searchMode: "problem", targetUser: "在宅ワーカー", problem: "デスクが狭い", selectionReason: "収納", searchKeywords: ["収納 ラック"] }));
assert.equal(searchContext.version, 1);
assert.equal(searchContext.selectionReason, "収納");
assert.equal(searchContext.origin, null);

const html = fs.readFileSync("index.html", "utf8");
assert.ok(html.includes('id="expandedSearch"') && html.includes('id="expandedSave"') && html.includes('id="expandedRetryFailed"') && html.includes('id="expandedFailures"'));
assert.ok(html.includes('id="searchForm"') && html.includes('id="rankingForm"'));
assert.ok(/src="src\/core\/expanded-search\.js(?:\?[^\"]+)?"/.test(html) && /src="src\/expanded-search-ui\.js(?:\?[^\"]+)?"/.test(html));
assert.ok(html.includes("expanded-search-compare-r1"), "comparison search changes use fresh cache identifiers");
const css = fs.readFileSync("style.css", "utf8");
assert.ok(css.includes(".expanded-search-fields") && css.includes("max-width: 620px"));
console.log("expanded search rules and UI structure: passed");
